"""Derive the provisional time standards from the VSR reference-tower trial (Rev02 slide 7).

Method (documented so the numbers are traceable):
  1. Relative action weights (man-seconds) are the SAME for every system (industry-typical relative
     effort; status: estimate). One trial number per system can calibrate exactly one parameter.
  2. Count the actions of the reference tower with the current engine (BoM + sequence rules).
  3. Scale factor k_s = trial man-seconds / weighted action count, per system.
  4. actions[s] = k_s x base weight. Written to data/time_standards/<system>.yaml.
Splitting the system difference across individual actions (e.g. AutoLock vs manual wedge) needs
phase-level field data (Annex A) -> calibration module, phase 3.

Usage: python scripts/derive_provisional_standards.py [--data-dir data]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from vsr.catalogue import load_bundle  # noqa: E402
from vsr.engine.bom import generate_items  # noqa: E402
from vsr.engine.layout import generate_layout  # noqa: E402
from vsr.reference import REFERENCE_TRIAL, reference_tower  # noqa: E402

BASE_WEIGHTS = {  # man-seconds per action, relative (estimate)
    "place_base_jack": 30, "place_standard": 45, "place_ledger": 30, "place_transom": 30,
    "place_guardrail": 25, "place_diagonal": 40, "place_deck": 25, "place_hatch": 60,
    "place_toe_board": 25, "place_bracket": 50, "place_tie": 240, "secure_wedge": 10,
    "advance_guardrail": 60,
}
CREW_EFF = {1: 0.85, 2: 0.95, 3: 1.0, 4: 1.0, 5: 1.0, 6: 0.95, 8: 0.90, 10: 0.85}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-dir", default=str(ROOT / "data"))
    a = ap.parse_args()
    bundle = load_bundle(a.data_dir)
    area = reference_tower()
    out_dir = Path(a.data_dir) / "time_standards"
    out_dir.mkdir(exist_ok=True)
    for sid, minutes in REFERENCE_TRIAL["minutes"].items():
        cat = bundle.catalogues[sid]
        lay = generate_layout(area, cat, None, bundle.common)
        items, _, _ = generate_items(lay, cat, area, bundle.common)
        counts: dict[str, int] = {}
        for it in items:
            if it.action in ("infill", "infill_coupler"):
                continue
            counts[it.action] = counts.get(it.action, 0) + it.qty
        counts["secure_wedge"] = sum(it.wedges for it in items)
        weighted = sum(BASE_WEIGHTS[k] * v for k, v in counts.items())
        target = minutes * 60 * REFERENCE_TRIAL["crew"]
        k = target / weighted
        doc = {
            "standard_id": f"TS-{sid}", "system_id": sid, "version": "PROV-2026.11-r1", "status": "provisional",
            "derivation": (f"Base relative weights x scale factor {k:.4f} so that the reference tower "
                           f"({REFERENCE_TRIAL['source']}) reproduces {minutes:.0f} min with "
                           f"{REFERENCE_TRIAL['crew']} fitters. Generated by scripts/derive_provisional_standards.py."),
            "crew_reference": REFERENCE_TRIAL["crew"], "unit": "man-seconds per action",
            "scale_factor": round(k, 6), "base_weights": BASE_WEIGHTS,
            "reference_counts": counts,
            "actions": {a_: round(BASE_WEIGHTS[a_] * k, 3) for a_ in BASE_WEIGHTS},
            "infill_crew_hours_per_unit": 4.5, "dismantle_factor": 0.6, "crew_efficiency": CREW_EFF,
        }
        p = out_dir / f"{sid.lower()}.yaml"
        p.write_text("# PROVISIONAL — derived from one trial point. Recalibrate with Annex A field data.\n"
                     + yaml.safe_dump(doc, sort_keys=False), encoding="utf-8")
        print(f"{sid}: weighted={weighted:.0f} man-s, target={target:.0f} man-s, k={k:.4f} -> {p.name}")
    # generic fallback for systems without own standard (k = 1)
    gen = {"standard_id": "TS-GENERIC", "system_id": "_GENERIC", "version": "PROV-2026.11-r1",
           "status": "provisional-generic",
           "derivation": "Base relative weights, scale 1.0. Used for systems without their own time standard.",
           "crew_reference": 5, "unit": "man-seconds per action", "scale_factor": 1.0, "base_weights": BASE_WEIGHTS,
           "actions": dict(BASE_WEIGHTS), "infill_crew_hours_per_unit": 4.5, "dismantle_factor": 0.6,
           "crew_efficiency": CREW_EFF}
    (out_dir / "_generic.yaml").write_text(yaml.safe_dump(gen, sort_keys=False), encoding="utf-8")


if __name__ == "__main__":
    main()
